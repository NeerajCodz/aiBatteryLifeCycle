"""Leakage-safe v3 SOH inference and exploratory scenario endpoints."""

from __future__ import annotations

from fastapi import APIRouter, HTTPException

from api.model_registry import registry_v3, classify_degradation, soh_to_color
from api.schemas import (
    V3PredictRequest, PredictResponse,
    V3BatchPredictRequest, BatchPredictResponse,
    RecommendationRequest, RecommendationResponse, SingleRecommendation,
)

router = APIRouter(prefix="/api/v3", tags=["v3-prediction"])


# ── Single prediction ────────────────────────────────────────────────────────
@router.post("/predict", response_model=PredictResponse)
async def predict_v3(req: V3PredictRequest):
    """Estimate current-cycle SOH from an observable partial discharge only."""
    features = req.model_dump(exclude={"battery_id", "model_name"})
    features["cycle_index"] = features.pop("cycle_number") - 1

    try:
        result = registry_v3.predict(features, req.model_name)
    except Exception as exc:
        raise HTTPException(status_code=500, detail=str(exc))

    return PredictResponse(
        battery_id=req.battery_id,
        cycle_number=req.cycle_number,
        soh_pct=result["soh_pct"],
        rul_cycles=None,
        degradation_state=result["degradation_state"],
        confidence_lower=None,
        confidence_upper=None,
        model_used=result["model_used"],
        model_version=result.get("model_version", "3.0"),
    )


# ── Batch prediction ─────────────────────────────────────────────────────────
@router.post("/predict/batch", response_model=BatchPredictResponse)
async def predict_batch_v3(req: V3BatchPredictRequest):
    """Predict SOH for multiple cycles using v3 models."""
    cycles = []
    for row in req.cycles:
        features = row.model_dump()
        if "cycle_number" in features and "cycle_index" not in features:
            features["cycle_index"] = features["cycle_number"] - 1
        cycles.append(features)
    results = registry_v3.predict_batch(req.battery_id, cycles)
    predictions = [
        PredictResponse(
            battery_id=req.battery_id,
            cycle_number=r["cycle_number"],
            soh_pct=r["soh_pct"],
            rul_cycles=None,
            degradation_state=r["degradation_state"],
            confidence_lower=None,
            confidence_upper=None,
            model_used=r["model_used"],
            model_version=r.get("model_version", "3.0"),
        )
        for r in results
    ]
    return BatchPredictResponse(battery_id=req.battery_id, predictions=predictions)


# ── Recommendations (v3) ─────────────────────────────────────────────────────
@router.post("/recommend", response_model=RecommendationResponse)
async def recommend_v3(req: RecommendationRequest):
    """Return transparent, *unvalidated* operating-condition scenarios.

    The revised v3 model estimates current-cycle SOH; it was not trained to
    predict intervention effects or RUL.  This endpoint therefore keeps the UI
    prototype usable without misrepresenting counterfactual recommendations as
    validated model outputs.  Values are generated by the documented toy law
    below and must not be used for battery control or safety decisions.
    """
    import itertools

    temps = [4.0, 24.0, 43.0]
    currents = [0.5, 1.0, 2.0, 4.0]
    cutoffs = [2.0, 2.2, 2.5, 2.7]

    def illustrative_rate(temp: float, current: float, cutoff: float) -> float:
        """Toy SOH-loss rate (%-points/cycle), not an estimated causal effect."""
        thermal = 1.0 + 0.0025 * (temp - 24.0) ** 2
        current_stress = 1.0 + 0.22 * max(current - 1.0, 0.0) ** 1.3
        depth = 1.0 + 0.35 * max(2.6 - cutoff, 0.0)
        return 0.06 * thermal * current_stress * depth

    def illustrative_rul(temp: float, current: float, cutoff: float) -> float:
        margin = max(req.current_soh - 70.0, 0.0)
        return margin / max(illustrative_rate(temp, current, cutoff), 1e-9)

    baseline_rul = illustrative_rul(req.ambient_temperature, 1.82, 2.61)

    candidates = []
    for t, c, v in itertools.product(temps, currents, cutoffs):
        rul = illustrative_rul(t, c, v)
        improvement = rul - baseline_rul
        candidates.append({
            "raw_rul": rul,
            "improvement": improvement,
            "temp": t,
            "current": c,
            "cutoff": v,
        })

    candidates.sort(
        key=lambda x: (
            x["improvement"] > 0,
            x["improvement"],
            x["raw_rul"],
            -abs(x["temp"] - 24.0),
            -x["current"],
        ),
        reverse=True,
    )
    top = candidates[: req.top_k]

    recs = []
    for rank, rec in enumerate(top, 1):
        rul = rec["raw_rul"]
        t = rec["temp"]
        c = rec["current"]
        v = rec["cutoff"]
        improvement = rec["improvement"]
        pct = (improvement / baseline_rul * 100) if baseline_rul > 0 else 0
        impact = "improves" if improvement > 0 else "does not improve"
        recs.append(SingleRecommendation(
            rank=rank,
            ambient_temperature=t,
            discharge_current=c,
            cutoff_voltage=v,
            predicted_rul=rul,
            rul_improvement=improvement,
            rul_improvement_pct=round(pct, 1),
            explanation=(
                f"Exploratory scenario: {t}°C, {c}A, cutoff {v}V gives an "
                f"illustrative ~{rul:.0f}-cycle margin; the toy law {impact} "
                f"that margin by {improvement:+.0f} cycles versus baseline."
            ),
        ))

    return RecommendationResponse(
        battery_id=req.battery_id,
        current_soh=req.current_soh,
        recommendations=recs,
        validation_status="exploratory_prototype",
        disclaimer=(
            "Not produced by the v3 SOH estimator and not a validated causal or "
            "RUL model. Do not use for charging, safety, or maintenance decisions."
        ),
    )


